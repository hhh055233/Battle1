// הבהרת צבעים כהים: בלי מפת סביבה גוף הנשק השחור נראה כמעט שחור לגמרי; מרימים את הכהים (גמא) כך שהצורה נשארת קריאה
const lift = (h) => {
  const r = (h >> 16) & 255, g = (h >> 8) & 255, bl = h & 255, l = 0.299 * r + 0.587 * g + 0.114 * bl;
  if (l >= 165) return h;
  const mx = Math.max(r, g, bl), mn = Math.min(r, g, bl), sat = mx ? (mx - mn) / mx : 0;
  const e = sat < 0.22 ? 0.55 : 0.2; // כהה וכמעט אפור (מתכת/פולימר): הרמה חזקה; צבעוני (עץ/זית): עדינה
  const k = Math.min(4.4, Math.pow(Math.max(l, 6) / 165, -e)), f = (v) => Math.min(255, Math.round(v * k));
  return (f(r) << 16) | (f(g) << 8) | f(bl);
};

// ---- משולשים מפרופיל (ear clipping) ----
const area2 = (P) => { let a = 0; for (let i = 0; i < P.length; i++) { const A = P[i], B = P[(i + 1) % P.length]; a += A[0] * B[1] - B[0] * A[1]; } return a; };
function triangulate(P) {
  const ix = P.map((_, i) => i), out = [];
  const cr = (a, b, c) => (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]);
  const inside = (p, a, b, c) => cr(a, b, p) >= -1e-12 && cr(b, c, p) >= -1e-12 && cr(c, a, p) >= -1e-12;
  let guard = 0;
  while (ix.length > 3 && guard++ < 600) {
    let cut = false;
    for (let i = 0; i < ix.length; i++) {
      const i0 = ix[(i + ix.length - 1) % ix.length], i1 = ix[i], i2 = ix[(i + 1) % ix.length], a = P[i0], bb = P[i1], c = P[i2];
      if (cr(a, bb, c) <= 1e-12) continue;
      let ok = true;
      for (const j of ix) if (j !== i0 && j !== i1 && j !== i2 && inside(P[j], a, bb, c)) { ok = false; break; }
      if (!ok) continue;
      out.push([i0, i1, i2]); ix.splice(i, 1); cut = true; break;
    }
    if (!cut) break;
  }
  if (ix.length === 3) out.push([ix[0], ix[1], ix[2]]);
  return out;
}

// פרופיל צד [[z,y],...] שמוצא לאורך X מ-x0 עד x1 (קצוות קשיחים, נורמלים שטוחים)
function prism(b, poly, x0, x1, c, k = 'm') {
  let P = poly; if (area2(P) < 0) P = P.slice().reverse();
  const p = b.part(k), cc = col3(lift(c)), n = P.length;
  const V = (x, y, z, nx, ny, nz) => { p.pos.push(x, y, z); p.nor.push(nx, ny, nz); p.col.push(cc[0], cc[1], cc[2]); return p.pos.length / 3 - 1; };
  for (let i = 0; i < n; i++) {
    const A = P[i], B = P[(i + 1) % n], dz = B[0] - A[0], dy = B[1] - A[1], l = Math.hypot(dz, dy) || 1, nz = dy / l, ny = -dz / l;
    const a0 = V(x0, A[1], A[0], 0, ny, nz), a1 = V(x1, A[1], A[0], 0, ny, nz), b1 = V(x1, B[1], B[0], 0, ny, nz), b0 = V(x0, B[1], B[0], 0, ny, nz);
    p.idx.push(a0, a1, b1, a0, b1, b0);
  }
  for (const [i, j, m] of triangulate(P)) {
    const a = V(x1, P[i][1], P[i][0], 1, 0, 0), bb = V(x1, P[j][1], P[j][0], 1, 0, 0), cc2 = V(x1, P[m][1], P[m][0], 1, 0, 0);
    p.idx.push(a, cc2, bb);
    const a2 = V(x0, P[i][1], P[i][0], -1, 0, 0), b2 = V(x0, P[j][1], P[j][0], -1, 0, 0), c2 = V(x0, P[m][1], P[m][0], -1, 0, 0);
    p.idx.push(a2, b2, c2);
  }
}

const PR = (b, pts, w, c, k = 'm', x = 0) => prism(b, pts, x - w / 2, x + w / 2, c, k);
const BX = (b, w, h, d, x, y, z, c, k = 'm', r) => b.add(BOX(), { s: [w, h, d], p: [x, y, z], r: r || [0, 0, 0], c }, k);
