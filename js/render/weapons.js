const TB = (b, z0, z1, r0, r1, x, y, c, k = 'x', seg = 14, open = false) => b.add(CYLG(r0, r1, seg, open), { s: [1, z1 - z0, 1], r: [Math.PI / 2, 0, 0], p: [x, y, (z0 + z1) / 2], c }, k);
