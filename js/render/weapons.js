const CACHE = new Map();

// scope: 'red' | 'x2' | 'x4' | 'x8' | undefined -> כוונת מורכבת על הפס (אם לנשק יש פס/מקום)
export function buildWeapon(id, scope) {
  const fn = BUILD[id] || BUILD.m416;
  const key = id + '|' + (scope || '');
  let e = CACHE.get(key);
  if (!e) {
    const b = new Builder();
    const add0 = b.add.bind(b);
    b.add = (geo, o, k) => add0(geo, o && o.c != null ? Object.assign({}, o, { c: lift(o.c) }) : o, k);
    const meta = fn(b);
    let sightY = meta.sightY;
    if (scope && meta.scopeZ != null && !meta.builtinScope) {
      const railY = meta.railY != null ? meta.railY : meta.sightY - 0.026;
      sightY = optic(b, scope, meta.scopeZ, railY);
    }
    let zmin = 1e9, zmax = -1e9;
    for (const q of b.parts.values()) for (let i = 2; i < q.pos.length; i += 3) { if (q.pos[i] < zmin) zmin = q.pos[i]; if (q.pos[i] > zmax) zmax = q.pos[i]; }
    const grp = b.build(MATS());
    e = { grp, meta, sightY, zmin, zmax };
    CACHE.set(key, e);
  }
  const g = new THREE.Group();
  for (const m of e.grp.children) { const mesh = new THREE.Mesh(m.geometry, m.material); mesh.castShadow = true; g.add(mesh); }
  const M = e.meta, v = (a) => new THREE.Vector3(a[0], a[1], a[2]);
  g.userData = { muzzle: v(M.muzzle), fore: v(M.fore), grip: v(M.grip), len: -M.muzzle[2], sightY: e.sightY, cz: (e.zmin + e.zmax) / 2, zlen: e.zmax - e.zmin };
  return g;
}
